/**
 * Checks the CSS Module class names `vite.cssModules.mjs` generates. `npm run check:css`.
 *
 * Two things can go wrong with a scheme that turns a path into a class name, and neither is visible
 * in the running app until styles leak between components:
 *
 * - **Two modules collide.** The name is `rwp-<module path>-<local>`, so `.dashboard-header` in
 *   `src/components/dashboard/Dashboard.module.css` and in `src/components/Dashboard/Dashboard.module.css`
 *   would be one class. Kebab-casing is what makes this possible at all (`SectionAI` and `section-ai`
 *   are the same slug), which is why it is worth a check rather than an argument.
 * - **A generated name takes over a global one.** The `rwp-*`, `rwpb-*` and `rwpt-*` names are
 *   documented as stable hooks (README, Theme Editor help, snippet completion) and `theme.css` wins
 *   against a module rule on the same element by using two classes. A module class that happened to
 *   be called `rwp-post-card` would break both at once.
 *
 * The local names come from a regex over the stylesheet, so a class written only inside `:global(…)`
 * or produced by `composes:` is not counted here; that is fine, since both keep working whatever the
 * generator returns. Exit code 1 on either problem, with the file and the local name.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { scopedClassName } from './vite.cssModules.mjs'

const root = fileURLToPath(new URL('.', import.meta.url))

/** Folders that hold no first-party source: dependencies, build output, deployment config. */
const skipDirectories = new Set(['node_modules', '.git', '.vercel', '.vscode', 'dist', 'server-dist'])

/** Every file under the checkout, skipping the folders above. `src` and `plugins` are walked. */
function walk(directory, visit) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(directory, entry.name)
    if (entry.isDirectory()) {
      if (!skipDirectories.has(entry.name)) walk(full, visit)
    } else {
      visit(full)
    }
  }
}

/** The class selectors a stylesheet declares (`.foo`, `.foo-bar`), in order and de-duplicated. */
function localNames(css) {
  const names = []
  for (const match of css.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) {
    if (!names.includes(match[1])) names.push(match[1])
  }
  return names
}

const owners = new Map()
const moduleFiles = []
const globalNames = new Set()

walk(root, (file) => {
  const relative = path.relative(root, file).replace(/\\/g, '/')
  if (/\.module\.css$/i.test(file)) {
    moduleFiles.push(relative)
    const css = fs.readFileSync(file, 'utf8')
    for (const local of localNames(css)) {
      const name = scopedClassName(local, file)
      if (!owners.has(name)) owners.set(name, [])
      owners.get(name).push(`${relative} .${local}`)
    }
    return
  }
  // These two files define the scheme rather than use it, and they name generated classes on purpose —
  // this one explains what `.rwp-public-home-containerFull` is. Scanning them would flag the docs.
  if (file.endsWith(`vite.cssModules.mjs`) || file.endsWith(`vite.cssModules.check.mjs`)) return
  // Global stylesheets, plus the code that declares hooks and puts these classes on elements. Not the
  // docs: a README or CLAUDE.md example like `.rwp-public-home-containerFull` is a generated class
  // named in prose, not a class anybody declares.
  if (/\.md$/i.test(file) || !/\.(css|ts|tsx|js|jsx|mjs|html)$/i.test(file)) return
  // The token runs to the end of the name, uppercase included, because a generated name keeps the
  // local class as written (`.containerFull`, not `.container-full`). Truncating at the capital would
  // turn a documented example into a name that `PublicHome.module.css .container` really does use.
  for (const match of fs.readFileSync(file, 'utf8').matchAll(/\.(rw[pb]?[A-Za-z0-9_]*(?:-[A-Za-z0-9_]+)*)/g)) {
    globalNames.add(match[1])
  }
})

const collisions = [...owners.entries()].filter(([, found]) => found.length > 1)
const shadows = [...owners.keys()].filter((name) => globalNames.has(name)).sort()

console.log(`css modules: ${moduleFiles.length}, classes: ${owners.size}`)
console.log(`hooks and classes outside CSS Modules: ${globalNames.size}`)

for (const [name, found] of collisions) {
  console.error(`collision: '${name}' is generated by more than one declaration:\n  ${found.join('\n  ')}`)
}
for (const name of shadows) {
  console.error(`shadow: '${name}' is generated by a module and already exists as a global class:\n  ${owners.get(name).join('\n  ')}`)
}

if (collisions.length || shadows.length) {
  console.error(`\n${collisions.length + shadows.length} problem(s). Rename the module, its folder or the local class — do not fork the naming scheme in vite.cssModules.mjs.`)
  process.exit(1)
}
console.log('ok — every generated class is unique and none takes over a global name')
