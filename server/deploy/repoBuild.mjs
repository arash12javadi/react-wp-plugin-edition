/**
 * Building *this* site, with one more plugin in it, on this machine.
 *
 * Why this exists at all
 * ---------------------
 * A deployed React-WP site cannot install a plugin by copying files: the plugin is TypeScript that has to be
 * compiled into the browser bundle and into the `api/` function bundles, and only a machine with the source and
 * a Node toolchain can do that. On a Vercel deployment that machine does not exist — a function may not run
 * `npm ci`, has no repository checkout and writes to a read-only filesystem — which is exactly why the
 * customer-facing path pairs a *build environment* and hands the payload over (`scripts/rwpBuildWorker.mjs`).
 *
 * On a self-hosted deployment (`npm start`, the Hono host, Docker) the machine does exist: the process is
 * running inside the checkout. For that case this module is the whole of the "build it here" path — read the
 * repository into a `Map`, drop the plugin into `plugins/<id>/`, register its server module, and run the same
 * `buildDeployPayload()` + obfuscation + allowlist the installer's own provisioning runs.
 *
 * The allowlist is what makes this safe to expose over a route: whatever the plugin's ZIP contained, only
 * `dist/`, `api/*.mjs` and the manifests may leave, so a package cannot publish the site's `src/` or `server/`.
 */
import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { addServerPluginImportToSource } from '../serverPluginImports.mjs';
import { DeployError } from './errors.mjs';
import { obfuscateBuiltBundle, obfuscationEnabled } from './obfuscate.mjs';
import { assertDeployPayload, buildDeployPayload } from './prebuilt.mjs';

const str = (value) => (typeof value === 'string' ? value.trim() : '');

/**
 * What a build never needs, and what must never be read into memory: the dependency tree, the output of a
 * previous build, the site's own data, and the scratch/state directories.
 */
const SKIPPED_DIRECTORIES = new Set([
  'node_modules', '.git', '.github', 'dist', 'build', 'data', 'state', 'coverage',
  '.rwp-tmp', '.vercel', '.vscode',
]);

const MAX_FILE_BYTES = 8 * 1024 * 1024;
const MAX_TOTAL_BYTES = 96 * 1024 * 1024;
const MAX_FILES = 12_000;

/**
 * The repository as a `Map<path, Buffer>`, which is what `buildDeployPayload()` consumes.
 *
 * `public/` is included because a site's images and fonts are part of what it serves; everything skipped is
 * either regenerated by the build or belongs to the machine rather than the project. A `.env` file is never
 * read: the build is given its variables explicitly (`clientBuildEnv`).
 */
export async function readRepoFiles({ root = process.cwd(), log = () => {} } = {}) {
  const files = new Map();
  let total = 0;

  async function walk(directory, prefix) {
    let entries;
    try {
      entries = await readdir(directory, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (SKIPPED_DIRECTORIES.has(relative) || SKIPPED_DIRECTORIES.has(entry.name)) continue;
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        await walk(absolute, relative);
        continue;
      }
      if (!entry.isFile()) continue;
      // A `.env` file is the machine's configuration, not the project's: `clientBuildEnv` decides what a bundle
      // may be built with, and a secret read here would end up in a payload.
      if (/^(?:\.env(?:\.|$)|.*\.log$)/i.test(entry.name)) continue;
      const info = await readFile(absolute).catch(() => null);
      if (!info) continue;
      if (info.length > MAX_FILE_BYTES) {
        log(`skipping ${relative}: ${Math.round(info.length / 1024)} KB is over the per-file limit`);
        continue;
      }
      total += info.length;
      if (total > MAX_TOTAL_BYTES) {
        throw new DeployError(413, 'This repository is larger than a build payload may be, so it cannot be built into a deployment from here. Remove large files from public/ or install from a build worker.', { code: 'build_repo_too_large' });
      }
      if (files.size >= MAX_FILES) {
        throw new DeployError(413, `This repository has more than ${MAX_FILES} files, which is more than a build payload may carry.`, { code: 'build_repo_too_many_files' });
      }
      files.set(relative, info);
    }
  }

  await walk(root, '');
  return files;
}

/**
 * The variables a browser bundle may be built with: `VITE_*`, and nothing else.
 *
 * `buildDeployPayload()` deliberately drops every inherited secret before it adds back the environment it is
 * given, so passing the whole `process.env` would undo that protection. What Vite inlines is `VITE_*`, which is
 * also what `vite.config.js` bakes into `window.__REACT_WP_CONFIG__`.
 */
export const clientBuildEnv = (env = process.env || {}) =>
  Object.fromEntries(Object.entries(env).filter(([key, value]) => key.startsWith('VITE_') && typeof value === 'string' && value));

/** The plugin's own `.sql` files travel nowhere: schema is applied by an explicit, backed-up migration. */
const isSql = (name) => name.toLowerCase().endsWith('.sql');

/**
 * Builds the site with one plugin added, and returns the deployable payload.
 *
 * `entries` is a plugin ZIP's `Map<path, Buffer>` from `unpack()`. The plugin's `.sql` files are dropped rather
 * than compiled: they are applied by `applyMigrations()` with a human's consent, not shipped to the customer's
 * Vercel project, where they would be readable and useless.
 */
export async function buildSiteWithPlugin({
  repoFiles,
  pluginId,
  entries,
  env = {},
  version = '',
  label = 'this site',
  log = () => {},
  steps = {},
  timeoutMs = undefined,
}) {
  const id = str(pluginId);
  if (!(repoFiles instanceof Map) || repoFiles.size === 0) {
    throw new DeployError(500, 'The site\'s source could not be read, so the plugin cannot be compiled into it. This host builds from a checkout: run the installer on a server started with npm start.', { code: 'build_source_missing' });
  }
  if (!(entries instanceof Map) || entries.size === 0) {
    throw new DeployError(400, 'The plugin package is empty, so there is nothing to install.', { code: 'build_plugin_empty' });
  }

  const source = new Map(repoFiles);
  for (const [name, bytes] of entries) {
    if (isSql(name)) continue;
    source.set(`plugins/${id}/${name}`, Buffer.isBuffer(bytes) ? bytes : Buffer.from(bytes));
  }
  // A plugin with server routes has to be registered, or its `api/plugins` calls answer 404 on the deployed
  // site. The edit is the same one the disk installer makes, applied to the file inside the map instead of to
  // the file on disk — nothing in this process's own checkout is touched.
  if (entries.has('server.mjs')) {
    const registry = source.get('server/plugins.mjs');
    if (!registry) {
      throw new DeployError(500, 'This site has no server/plugins.mjs, so a plugin with server routes cannot be registered. Deploy the plugin from the repository instead.', { code: 'build_registry_missing' });
    }
    source.set('server/plugins.mjs', Buffer.from(addServerPluginImportToSource(registry.toString('utf8'), id), 'utf8'));
  }

  const built = await buildDeployPayload({ source, label, version, env, steps, timeoutMs, log });
  const files = built.files;
  const lock = obfuscationEnabled() ? await obfuscateBuiltBundle(files) : null;
  if (lock && !lock.obfuscated && !lock.alreadyLocked && lock.protectedChunks.length === 0) {
    throw new DeployError(502, 'The build produced no JavaScript the lock step could obscure, so it was not deployed: that payload would ship readable source.', { code: 'build_unlocked' });
  }
  assertDeployPayload(files, label);
  return { files, report: built.report, lock };
}

/** A short sentence about the build, for a job's step note. */
export function describeBuild({ report, lock } = {}) {
  const parts = [];
  if (report?.files) parts.push(`${report.files} deployable file(s)`);
  if (lock?.obfuscated) parts.push(`${lock.obfuscated} file(s) obfuscated`);
  return parts.join(', ');
}
