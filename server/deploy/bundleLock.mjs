/**
 * The build-time half of the lock: the step the installer writes *into* a deployed template so the
 * bundle Vercel compiles is obfuscated on the account that serves it.
 *
 * Why this has to exist at all — the reason every deployment shipped readable JavaScript:
 *
 *   1. The installer deploys a *source tree*. `templateSourceFiles()` fetches GitHub's
 *      `/repos/:owner/:repo/tarball/:ref`, which is a `git archive` of committed files: `dist/`,
 *      `build/` and `src/server-dist/` are in `.gitignore`, so the archive contains **no built
 *      JavaScript**. `obfuscateSourceTree()` looked for JavaScript under `dist/`, found none and
 *      returned the tree untouched, without an error.
 *   2. Vercel then runs `vercel.json` → `buildCommand: npm run build`, which compiles the clean
 *      TypeScript on the *customer's* account and serves the result. Whatever the installer did or did
 *      not obfuscate before the upload is irrelevant to that bundle, because it did not exist yet.
 *
 * So the lock has to run twice, and this module is the second half:
 *
 *   - `obfuscateBuiltBundle()` (./obfuscate.mjs) rewrites build output that *does* travel in the
 *     payload — a release that commits `dist/`, or a Build Output API tree — before the upload.
 *   - `installBundleLockStep()` (here) adds `scripts/rwp-lock-bundle.mjs` to the payload and chains it
 *     into the build, so `npm run build` ends by obfuscating the `dist/` Vite just emitted. This is
 *     the pass that fixes the default source release.
 *
 * The script is injected rather than living in this repository because this plugin is
 * development-edition-only (`export-ignore` in `.gitattributes`): nothing under
 * `plugins/rwp-saas-installer/` may travel in a release, so the payload is written at deploy time.
 * It needs no extra dependency — `javascript-obfuscator` is already a dependency of the template,
 * and `installBundleLockStep()` re-asserts it if a release drops it.
 */
import { defaultObfuscatorOptions, PROTECTED_CHUNK_RULE, RESERVED_NAME_RULE } from './obfuscate.mjs';

/** Where the step lands inside the deployed tree. */
export const BUNDLE_LOCK_PATH = 'scripts/rwp-lock-bundle.mjs';

/** The argument that identifies the step in a build command, used to chain exactly once. */
export const BUNDLE_LOCK_MARKER = 'rwp-lock-bundle.mjs';

/** The package the injected step imports; kept identical to this repository's dependency range. */
export const BUNDLE_LOCK_DEPENDENCY = { 'javascript-obfuscator': '^4.2.2' };

/**
 * The injected script, verbatim.
 *
 * Constraints that are easy to break and expensive to debug: it runs as the last step of `npm run
 * build` with no arguments, it is plain ESM in a `"type": "module"` package, and it must fail the
 * build (non-zero exit) rather than let a clean bundle through — a silent pass is the bug this whole
 * module exists to fix. `RWP_SAAS_OBFUSCATE=off` remains the one intentional way out, mirroring
 * ./obfuscate.mjs.
 */
const BUNDLE_LOCK_TEMPLATE = `/**
 * rwp-lock-bundle.mjs — written into this deployment by the RWP SaaS installer.
 *
 * Runs as the last step of npm run build and rewrites every JavaScript file the browser can download
 * (dist/, build/, out/, public/build/, .vercel/output/static/) with javascript-obfuscator, then
 * deletes the source maps that would hand the original code back. The rich-text editor's chunk
 * (Tiptap/ProseMirror) is the one exception and is left readable on purpose: transforming it renames
 * the classes its own static create() factories construct, and the editor then fails in the browser
 * with "is not a constructor".
 *
 * Do not edit this file in the deployed project: the next release replaces it. Set
 * RWP_SAAS_OBFUSCATE=off to skip the transform (development only).
 */
import { readdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** The project root: this file lives in <root>/scripts/. */
const ROOT = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUTPUT_DIRS = ['dist', 'build', 'out', 'public/build', '.vercel/output/static'];
const JS = /\\.(?:mjs|cjs|js)$/i;
const SOURCE_MAP = /\\.map$/i;

/**
 * Files that already read _0x... are left alone: selfDefending output must not be transformed a
 * second time, so re-running this step over an old dist/ (an incremental build that did not clean its
 * output directory) would break the site instead of hardening it.
 */
const looksLocked = (source) =>
  /function\\s+_0x[0-9a-f]{2,}\\s*\\(/.test(source) && (source.match(/_0x[0-9a-f]{2,}/g) || []).length >= 10;

/**
 * Exactly the installer's own profile: the placeholder below is filled in from
 * plugins/rwp-saas-installer/obfuscate.mjs at deploy time, so the two passes cannot drift apart.
 */
const PROFILE = __RWP_PROFILE__;

/**
 * The chunks the installer leaves readable, filled in from the same module as the profile: the
 * rich-text editor's (Tiptap/ProseMirror). Transforming that chunk renames the classes its own static
 * \`create()\` factories construct, and the editor then throws "is not a constructor" on first render.
 */
const PROTECTED = __RWP_PROTECTED__;
const PROTECTED_NAME = new RegExp(PROTECTED.module, PROTECTED.flags);

/**
 * The names a chunk cannot have renamed, filled in from the same module as the profile.
 *
 * A named class expression that references its own name — "@supabase/supabase-js"'s
 * wi = class e { constructor(){ ... e.nextInstanceID[storageKey] ... } } — is mis-read by the renamer:
 * it leaves the inner name e alone, renames the import { n as e } sitting next to it, and rewrites the
 * reference inside the constructor to the *import's* name. The deployed site then threw "Cannot read
 * properties of undefined (reading 'sb-<ref>-auth-token')" at createClient() and could not reach its
 * database at all. Reserving every class/function name in the chunk keeps that reference resolving to
 * the class itself; minified build output names are one or two letters, so nothing readable is exposed.
 */
const RESERVED = __RWP_RESERVED__;

const anchorName = (name) => '^' + name.split('$').join('\\\\$') + '$';

function reservedNamesFor(source) {
  const names = new Set();
  const pattern = new RegExp(RESERVED.named, RESERVED.flags);
  let match;
  while ((match = pattern.exec(source)) !== null) names.add(anchorName(match[1]));
  return [...names];
}

function protectedReason(name, source) {
  if (PROTECTED_NAME.test(name.split('/').pop() || '')) return 'the rich-text editor chunk';
  let seen = 0;
  for (const marker of PROTECTED.markers) {
    if (source.includes(marker)) seen += 1;
    if (seen >= PROTECTED.threshold) return 'the rich-text editor code it contains';
  }
  return '';
}

const line = (message) => console.log('[rwp-lock] ' + message);

const enabled = () => String(process.env.RWP_SAAS_OBFUSCATE || 'on').trim().toLowerCase() !== 'off';

async function isDirectory(target) {
  try {
    return (await stat(target)).isDirectory();
  } catch {
    return false;
  }
}

async function walk(dir, found) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (/^(?:node_modules|\\.git)$/.test(entry.name)) continue;
      await walk(full, found);
    } else if (entry.isFile()) {
      found.push(full);
    }
  }
  return found;
}

/** Both public shapes of the package: default export in v2/v3, named obfuscate() in v4. */
async function loadObfuscator() {
  const mod = await import('javascript-obfuscator');
  const obfuscate = mod.obfuscate || (mod.default && mod.default.obfuscate) || mod.default;
  if (typeof obfuscate !== 'function') {
    throw new Error('javascript-obfuscator did not expose obfuscate(). Keep it in the "dependencies" of package.json — the build output cannot be locked without it.');
  }
  return obfuscate;
}

async function main() {
  if (!enabled()) {
    line('RWP_SAAS_OBFUSCATE=off — the build output is left readable on purpose.');
    return;
  }

  const files = [];
  for (const dir of OUTPUT_DIRS) {
    const full = path.join(ROOT, dir);
    if (await isDirectory(full)) await walk(full, files);
  }
  const bundle = files.filter((file) => JS.test(file) && !SOURCE_MAP.test(file));
  const maps = files.filter((file) => SOURCE_MAP.test(file));

  const obfuscate = await loadObfuscator();
  let locked = 0;
  let kept = 0;
  let readable = 0;
  for (const file of bundle) {
    const relative = path.relative(ROOT, file).split(path.sep).join('/');
    const source = await readFile(file, 'utf8');
    if (!source.trim()) continue;
    if (looksLocked(source)) {
      kept += 1;
      line(relative + ' already locked, left alone');
      continue;
    }
    const reason = protectedReason(relative, source);
    if (reason) {
      readable += 1;
      line(relative + ' left readable: it is ' + reason + ', and transforming it breaks its class constructors.');
      continue;
    }
    const result = obfuscate(source, { ...PROFILE, reservedNames: reservedNamesFor(source), seed: locked });
    await writeFile(file, result.getObfuscatedCode(), 'utf8');
    locked += 1;
    line(relative + ' locked (' + Math.round(source.length / 1024) + ' KB)');
  }
  // A map hands the original source straight back, so it goes even if nothing else changed.
  for (const file of maps) await rm(file, { force: true });

  if (locked + kept + readable === 0) {
    console.error('[rwp-lock] No build output to lock: looked in ' + OUTPUT_DIRS.join(', ') + '. The site would ship readable JavaScript, so the build stops here.');
    process.exitCode = 1;
    return;
  }
  line('locked ' + locked + ' bundle file(s)' + (kept ? ', ' + kept + ' already locked' : '') + (readable ? ', ' + readable + ' rich-text editor chunk(s) left readable on purpose' : '') + ', removed ' + maps.length + ' source map(s).');
}

main().catch((error) => {
  console.error('[rwp-lock] ' + (error && error.message ? error.message : String(error)));
  process.exitCode = 1;
});
`;

/**
 * The profile, serialised out of ./obfuscate.mjs rather than written down twice.
 *
 * A second copy of the knobs would drift — someone tightens `--strong` in the installer's profile and
 * the build-time pass quietly keeps the old one, so half a deployment is locked with a weaker setting
 * than the other half. `seed` is dropped: the step seeds each file itself so two chunks never share a
 * string array.
 */
const PROFILE_LITERAL = (() => {
  const profile = { ...defaultObfuscatorOptions() };
  delete profile.seed;
  return JSON.stringify(profile, null, 2);
})();

/**
 * The editor-chunk rule, serialised out of ./obfuscate.mjs for the same reason as the profile: this
 * step runs on the customer's Vercel build, where `plugins/rwp-saas-installer/` does not exist, so the
 * rule has to travel in the script — but only ever as a copy of the one in this repository.
 */
const PROTECTED_LITERAL = JSON.stringify(PROTECTED_CHUNK_RULE, null, 2);

/** The reserved-name rule, serialised for the same reason: the step must reserve the same bindings. */
const RESERVED_LITERAL = JSON.stringify(RESERVED_NAME_RULE, null, 2);

/** The injected script with its profile, its protected-chunk rule and its reserved-name rule filled in
 * — the exact bytes `installBundleLockStep()` ships. Function replacements, so a `$` inside a reserved
 * string (the option entries are regexes) can never be read as a `$&`/`$'` replacement pattern. */
export const BUNDLE_LOCK_SOURCE = BUNDLE_LOCK_TEMPLATE
  .replace('__RWP_PROFILE__', () => PROFILE_LITERAL)
  .replace('__RWP_PROTECTED__', () => PROTECTED_LITERAL)
  .replace('__RWP_RESERVED__', () => RESERVED_LITERAL);

/** Parses a JSON entry of the payload, or returns `null` when it is missing or not an object. */
function parseEntry(files, name) {
  const bytes = files.get(name);
  if (!bytes) return null;
  try {
    const value = JSON.parse(bytes.toString('utf8'));
    return value && typeof value === 'object' && !Array.isArray(value) ? value : null;
  } catch {
    return null;
  }
}

/** Writes a JSON entry back, formatted the way the repository's own files are. */
function writeEntry(files, name, value) {
  files.set(name, Buffer.from(`${JSON.stringify(value, null, 2)}\n`, 'utf8'));
}

/**
 * Writes the lock step into a payload and wires it into whatever command Vercel will actually run.
 *
 * Returns `{ installed, command, chained, reason }`:
 *   - `installed` — the payload now carries the step *and* something invokes it.
 *   - `chained`   — which file was rewritten (`package.json` or `vercel.json`), for the report.
 *   - `reason`    — why it could not be wired, when `installed` is false.
 *
 * Two shapes are handled because a template may build through either: `package.json`'s `build` script
 * (Vercel's default, and what this repository's `vercel.json` calls) and a `vercel.json` `buildCommand`
 * that names something else. The step is chained at most once, so re-deploying an already-locked
 * release does not append it twice.
 */
export function installBundleLockStep(files) {
  const command = `node ${BUNDLE_LOCK_PATH}`;
  if (!(files instanceof Map)) return { installed: false, command, chained: '', reason: 'the payload is not a file map' };

  const packageJson = parseEntry(files, 'package.json');
  if (!packageJson) return { installed: false, command, chained: '', reason: 'its package.json is missing or is not valid JSON' };

  files.set(BUNDLE_LOCK_PATH, Buffer.from(BUNDLE_LOCK_SOURCE, 'utf8'));

  const scripts = packageJson.scripts && typeof packageJson.scripts === 'object' && !Array.isArray(packageJson.scripts)
    ? { ...packageJson.scripts }
    : {};
  const build = typeof scripts.build === 'string' ? scripts.build : '';

  let chained = '';
  let needsPackageChain = !build.includes(BUNDLE_LOCK_MARKER);

  // `vercel.json` is the authority when it names its own command: appending the step to a build script
  // Vercel never runs would be a lock that exists and never fires, which is worse than none.
  const vercel = parseEntry(files, 'vercel.json');
  if (vercel && typeof vercel.buildCommand === 'string' && vercel.buildCommand.trim()) {
    const buildCommand = vercel.buildCommand.trim();
    if (buildCommand.includes(BUNDLE_LOCK_MARKER)) {
      needsPackageChain = false;
      chained = 'vercel.json';
    } else if (!/\bnpm\s+run\s+build\b/.test(buildCommand)) {
      vercel.buildCommand = `${buildCommand} && ${command}`;
      writeEntry(files, 'vercel.json', vercel);
      needsPackageChain = false;
      chained = 'vercel.json';
    }
  }

  if (needsPackageChain) {
    if (!build) {
      return { installed: false, command, chained, reason: 'its package.json has no build script to chain the step onto' };
    }
    scripts.build = `${build} && ${command}`;
    chained = chained || 'package.json';
  }
  packageJson.scripts = scripts;

  // The step imports javascript-obfuscator directly; a release that dropped the dependency would fail
  // its build instead of silently skipping the lock, so it is re-asserted here.
  const dependencies = packageJson.dependencies && typeof packageJson.dependencies === 'object' && !Array.isArray(packageJson.dependencies)
    ? { ...packageJson.dependencies }
    : {};
  for (const [name, range] of Object.entries(BUNDLE_LOCK_DEPENDENCY)) {
    if (!dependencies[name] && !packageJson.devDependencies?.[name]) dependencies[name] = range;
  }
  packageJson.dependencies = dependencies;

  writeEntry(files, 'package.json', packageJson);
  return { installed: true, command, chained, reason: '' };
}

